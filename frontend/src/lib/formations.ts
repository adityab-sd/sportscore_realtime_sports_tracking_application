/** Normalise formation string: "433" → "4-3-3", "4-2-3-1" stays as-is */
export function normaliseFormation(raw: string): string {
  const digits = raw.replace(/[^0-9]/g, "");
  if (digits.length < 3) return "4-4-2";
  return digits.split("").join("-");
}

/** Look up coords for a formation; falls back to 4-4-2 */
export function getFormationCoords(formation: string): Formation {
  const key = normaliseFormation(formation);
  return FORMATIONS[key] ?? FORMATIONS["4-4-2"];
}